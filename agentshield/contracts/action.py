"""
AgentShield AI — Action Request Contract.

This module defines the normalized action request submitted by any
integration (SDK adapter, MCP proxy, or direct API caller) when an
AI agent attempts to invoke a tool.

TRUST BOUNDARY NOTICE
─────────────────────
Several fields in this contract represent identity claims that originate
from the integration layer rather than from the agent itself.  The
following fields MUST be derived from authenticated, server-side connector
context — they MUST NOT be accepted verbatim from agent-supplied data:

    • tenant_id    — Determined from the authenticated API key / OAuth token.
    • agent_id     — Registered and assigned by the AgentShield backend at
                     connector registration time.
    • user_id      — Derived from the authenticated session context.
    • session_id   — Issued by the backend; not generated by the agent.

Fields supplied by the agent request payload (tool_name, operation,
arguments, etc.) are considered UNTRUSTED INPUT and must be validated and
sanitized by the security core before any evaluation or execution.

The connector / integration layer is responsible for enriching the request
with server-verified identity information before forwarding it to the
security evaluation API.
"""

from __future__ import annotations

import uuid
from datetime import UTC, datetime
from typing import Annotated, Any

from pydantic import BaseModel, Field, field_validator, model_validator

from agentshield.contracts.enums import IntegrationType, ToolCategory

# ---------------------------------------------------------------------------
# Field length limits — guard against oversized payloads from untrusted agents
# ---------------------------------------------------------------------------
_MAX_TOOL_NAME_LEN = 128
_MAX_OPERATION_LEN = 128
_MAX_REASON_LEN = 1024
_MAX_ARGS_SIZE = 65_536  # bytes (approximate, enforced via JSON string length)


class SourceContext(BaseModel):
    """Optional provenance metadata attached by the integration layer.

    This information helps human reviewers and audit records understand
    *where* a request came from without exposing raw agent internals.
    All fields are optional so that integrations can supply what they know.
    """

    agent_framework: str | None = Field(
        default=None,
        max_length=64,
        description="The AI framework driving the agent (e.g. 'openai-agents', 'langgraph').",
    )
    agent_version: str | None = Field(
        default=None,
        max_length=32,
        description="Version string of the agent framework.",
    )
    connector_version: str | None = Field(
        default=None,
        max_length=32,
        description="Version of the AgentShield integration adapter.",
    )
    originating_ip: str | None = Field(
        default=None,
        max_length=45,
        description="IP address of the host where the agent is running (set by the connector).",
    )
    task_description: str | None = Field(
        default=None,
        max_length=512,
        description=(
            "High-level description of the agent task at the time of the request. "
            "Useful for human reviewers but MUST NOT be trusted for security decisions."
        ),
    )


class ActionRequest(BaseModel):
    """Normalized action request submitted to the AgentShield security core.

    This is the canonical contract used by all integration paths.  Every
    integration adapter (SDK or MCP) MUST map its native tool-call format
    to this structure before submitting it to the backend evaluation API.

    See the module docstring for the trust-boundary requirements on identity
    fields.
    """

    # ------------------------------------------------------------------
    # Request identity — generated by the connector, not the agent
    # ------------------------------------------------------------------

    request_id: Annotated[
        uuid.UUID,
        Field(
            default_factory=uuid.uuid4,
            description=(
                "Unique identifier for this request, generated by the integration layer. "
                "Used for correlation in audit logs and approval workflows."
            ),
        ),
    ]

    # ------------------------------------------------------------------
    # Identity context — MUST come from authenticated server-side context
    # ------------------------------------------------------------------

    tenant_id: Annotated[
        uuid.UUID,
        Field(
            description=(
                "[TRUST: SERVER-DERIVED] "
                "Identifier of the tenant that owns the agent. "
                "MUST be resolved from the authenticated API credential, "
                "never accepted from the agent request payload."
            )
        ),
    ]

    agent_id: Annotated[
        uuid.UUID,
        Field(
            description=(
                "[TRUST: SERVER-DERIVED] "
                "Registered identifier of the AI agent. "
                "MUST be assigned by the AgentShield backend at connector "
                "registration and not supplied by the agent itself."
            )
        ),
    ]

    user_id: Annotated[
        uuid.UUID | None,
        Field(
            default=None,
            description=(
                "[TRUST: SERVER-DERIVED] "
                "Identifier of the human user associated with the agent session, if any. "
                "MUST be derived from the authenticated session context."
            ),
        ),
    ]

    session_id: Annotated[
        uuid.UUID | None,
        Field(
            default=None,
            description=(
                "[TRUST: SERVER-DERIVED] "
                "Session identifier issued by the AgentShield backend. "
                "MUST NOT be generated or supplied by the agent."
            ),
        ),
    ]

    # ------------------------------------------------------------------
    # Integration metadata
    # ------------------------------------------------------------------

    integration_type: Annotated[
        IntegrationType,
        Field(
            description=(
                "The integration channel through which this request arrived. "
                "Set by the connector adapter."
            )
        ),
    ]

    # ------------------------------------------------------------------
    # Tool / action description — supplied by the agent (UNTRUSTED INPUT)
    # ------------------------------------------------------------------

    tool_name: Annotated[
        str,
        Field(
            min_length=1,
            max_length=_MAX_TOOL_NAME_LEN,
            description=(
                "[TRUST: AGENT-SUPPLIED — UNTRUSTED] "
                "Name of the tool the agent is requesting to invoke."
            ),
        ),
    ]

    tool_category: Annotated[
        ToolCategory,
        Field(
            default=ToolCategory.UNKNOWN,
            description=(
                "High-level category of the tool. "
                "May be supplied by the connector or inferred by the security core."
            ),
        ),
    ]

    operation: Annotated[
        str | None,
        Field(
            default=None,
            max_length=_MAX_OPERATION_LEN,
            description=(
                "[TRUST: AGENT-SUPPLIED — UNTRUSTED] "
                "Specific operation within the tool (e.g. 'read', 'write', 'delete')."
            ),
        ),
    ]

    arguments: Annotated[
        dict[str, Any],
        Field(
            default_factory=dict,
            description=(
                "[TRUST: AGENT-SUPPLIED — UNTRUSTED] "
                "Arguments to be passed to the tool. "
                "These MUST be validated by the security core before execution."
            ),
        ),
    ]

    # ------------------------------------------------------------------
    # Provenance / source context
    # ------------------------------------------------------------------

    source: Annotated[
        SourceContext | None,
        Field(
            default=None,
            description="Optional provenance metadata supplied by the integration layer.",
        ),
    ]

    # ------------------------------------------------------------------
    # Timing
    # ------------------------------------------------------------------

    timestamp: Annotated[
        datetime,
        Field(
            default_factory=lambda: datetime.now(UTC),
            description="UTC timestamp at which the request was created by the connector.",
        ),
    ]

    # ------------------------------------------------------------------
    # Validators
    # ------------------------------------------------------------------

    @field_validator("tool_name")
    @classmethod
    def tool_name_must_not_be_blank(cls, v: str) -> str:
        if not v.strip():
            raise ValueError("tool_name must not be blank or whitespace only.")
        return v.strip()

    @model_validator(mode="after")
    def arguments_size_limit(self) -> "ActionRequest":
        """Reject oversized argument payloads to prevent DoS from untrusted agents."""
        import json

        try:
            serialized = json.dumps(self.arguments)
        except (TypeError, ValueError) as exc:
            raise ValueError(f"arguments must be JSON-serializable: {exc}") from exc
        if len(serialized) > _MAX_ARGS_SIZE:
            raise ValueError(
                f"arguments payload exceeds maximum allowed size "
                f"({_MAX_ARGS_SIZE} bytes). Got {len(serialized)} bytes."
            )
        return self

    model_config = {
        "json_schema_extra": {
            "example": {
                "tenant_id": "00000000-0000-0000-0000-000000000001",
                "agent_id": "00000000-0000-0000-0000-000000000002",
                "integration_type": "SDK_OPENAI",
                "tool_name": "read_file",
                "tool_category": "FILE_SYSTEM",
                "operation": "read",
                "arguments": {"path": "/home/user/document.txt"},
            }
        }
    }
