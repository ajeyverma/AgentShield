"""
AgentShield AI — Security Decision Contract.

Defines the structure returned by the AgentShield security core after
evaluating an action request.

ENFORCEMENT GUARANTEE
─────────────────────
A SecurityDecision is produced exclusively by the AgentShield backend
security core.  It is never accepted from, generated by, or overrideable
by the AI agent or the integration client.

The integration layer is responsible for:
  1. Forwarding the ActionRequest to the backend.
  2. Receiving the SecurityDecision response.
  3. Obeying the decision — forwarding the tool call only on ALLOW,
     blocking it on BLOCK, and suspending execution on ASK_HUMAN.

The integration layer MUST NOT allow a client to forge or inject a
pre-computed ALLOW decision to bypass security evaluation.
"""

from __future__ import annotations

import uuid
from datetime import UTC, datetime
from typing import Annotated

from pydantic import BaseModel, Field

from agentshield.contracts.enums import Decision, RiskLevel


class PolicyMatch(BaseModel):
    """Details of a policy that contributed to the security decision."""

    policy_id: uuid.UUID = Field(description="Unique identifier of the matched policy.")
    policy_name: str = Field(max_length=128, description="Human-readable name of the policy.")
    rule_id: str | None = Field(
        default=None,
        max_length=128,
        description="Identifier of the specific rule within the policy that was triggered.",
    )


class SecurityDecision(BaseModel):
    """The authoritative security decision returned by the AgentShield backend.

    This object is the single point of truth for whether an action may
    proceed.  Every field is set by the backend; none may be supplied or
    modified by the requesting client.

    Usage flow:
        1. Integration adapter sends ActionRequest → backend.
        2. Backend evaluates and returns SecurityDecision.
        3. Adapter checks decision.decision:
            - ALLOW     → execute the tool call.
            - BLOCK     → reject immediately, return error to agent.
            - ASK_HUMAN → suspend agent execution and await approval_id resolution.
    """

    # ------------------------------------------------------------------
    # Correlation
    # ------------------------------------------------------------------

    request_id: Annotated[
        uuid.UUID,
        Field(description="Mirrors the request_id from the originating ActionRequest."),
    ]

    decision_id: Annotated[
        uuid.UUID,
        Field(
            default_factory=uuid.uuid4,
            description="Unique identifier for this specific decision record.",
        ),
    ]

    # ------------------------------------------------------------------
    # The decision
    # ------------------------------------------------------------------

    decision: Annotated[
        Decision,
        Field(description="The security decision: ALLOW, BLOCK, or ASK_HUMAN."),
    ]

    # ------------------------------------------------------------------
    # Risk assessment
    # ------------------------------------------------------------------

    risk_score: Annotated[
        float,
        Field(
            ge=0.0,
            le=100.0,
            description=(
                "Numeric risk score in the range [0, 100]. "
                "0 = no risk; 100 = maximum risk. "
                "The scoring algorithm is implemented in the risk engine (Phase 3+)."
            ),
        ),
    ]

    risk_level: Annotated[
        RiskLevel,
        Field(description="Qualitative risk classification derived from risk_score."),
    ]

    # ------------------------------------------------------------------
    # Explanation
    # ------------------------------------------------------------------

    reasons: Annotated[
        list[str],
        Field(
            default_factory=list,
            description=(
                "Human-readable explanations for the decision. "
                "Each entry describes one factor that influenced the outcome."
            ),
        ),
    ]

    # ------------------------------------------------------------------
    # Policy attribution
    # ------------------------------------------------------------------

    matched_policies: Annotated[
        list[PolicyMatch],
        Field(
            default_factory=list,
            description="Policies that matched the action request and influenced the decision.",
        ),
    ]

    # ------------------------------------------------------------------
    # Human approval (populated only when decision == ASK_HUMAN)
    # ------------------------------------------------------------------

    approval_required: Annotated[
        bool,
        Field(
            default=False,
            description="True when decision is ASK_HUMAN and human approval is required.",
        ),
    ]

    approval_id: Annotated[
        uuid.UUID | None,
        Field(
            default=None,
            description=(
                "Identifier of the pending approval request. "
                "Populated only when decision == ASK_HUMAN. "
                "The integration layer should poll or await this ID for resolution."
            ),
        ),
    ]

    approval_timeout_seconds: Annotated[
        int | None,
        Field(
            default=None,
            ge=1,
            description=(
                "Maximum time in seconds to wait for a human approval response. "
                "Populated only when decision == ASK_HUMAN."
            ),
        ),
    ]

    # ------------------------------------------------------------------
    # Timing
    # ------------------------------------------------------------------

    evaluated_at: Annotated[
        datetime,
        Field(
            default_factory=lambda: datetime.now(UTC),
            description="UTC timestamp at which the security evaluation completed.",
        ),
    ]

    evaluation_duration_ms: Annotated[
        float | None,
        Field(
            default=None,
            ge=0.0,
            description="Time taken by the security core to produce this decision, in milliseconds.",
        ),
    ]

    model_config = {
        "json_schema_extra": {
            "examples": [
                {
                    "request_id": "123e4567-e89b-12d3-a456-426614174000",
                    "decision": "ALLOW",
                    "risk_score": 5.0,
                    "risk_level": "LOW",
                    "reasons": ["Action matches approved policy for file reads in /home/user/."],
                    "matched_policies": [],
                    "approval_required": False,
                },
                {
                    "request_id": "123e4567-e89b-12d3-a456-426614174001",
                    "decision": "BLOCK",
                    "risk_score": 95.0,
                    "risk_level": "CRITICAL",
                    "reasons": ["Attempt to access /etc/passwd is prohibited by policy P-001."],
                    "matched_policies": [
                        {
                            "policy_id": "00000000-0000-0000-0000-000000000099",
                            "policy_name": "Block sensitive system file access",
                            "rule_id": "P-001-R-003",
                        }
                    ],
                    "approval_required": False,
                },
                {
                    "request_id": "123e4567-e89b-12d3-a456-426614174002",
                    "decision": "ASK_HUMAN",
                    "risk_score": 60.0,
                    "risk_level": "HIGH",
                    "reasons": ["File deletion outside the sandbox requires human approval."],
                    "matched_policies": [],
                    "approval_required": True,
                    "approval_id": "aaaaaaaa-bbbb-cccc-dddd-eeeeeeeeeeee",
                    "approval_timeout_seconds": 300,
                },
            ]
        }
    }
