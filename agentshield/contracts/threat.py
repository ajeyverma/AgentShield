"""
AgentShield AI — Threat Contracts (Phase 5).

Standardized Pydantic schemas and enums for threat findings, analysis results,
and detection metadata.
"""

from __future__ import annotations

import uuid
from datetime import UTC, datetime
from enum import Enum
from typing import Any

from pydantic import BaseModel, Field

from agentshield.contracts.provenance import ProvenanceContext


class ThreatCategory(str, Enum):
    """Standard threat categories."""

    PROMPT_INJECTION = "prompt_injection"
    DATA_LEAKAGE = "data_leakage"
    FILESYSTEM = "filesystem"
    DANGEROUS_COMMAND = "dangerous_command"
    SUSPICIOUS_NETWORK = "suspicious_network"
    BEHAVIORAL_ANOMALY = "behavioral_anomaly"
    SUSPICIOUS_ACTIVITY = "suspicious_activity"


class ThreatSeverity(str, Enum):
    """Qualitative threat severity."""

    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"


class ThreatConfidence(str, Enum):
    """Detection confidence level."""

    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"


class FindingStatus(str, Enum):
    """Triage and remediation status of a finding."""

    OPEN = "open"
    INVESTIGATING = "investigating"
    RESOLVED = "resolved"
    DISMISSED = "dismissed"


class ThreatFinding(BaseModel):
    """A single, explainable threat finding generated by a detector."""

    finding_id: uuid.UUID = Field(default_factory=uuid.uuid4)
    request_id: uuid.UUID
    user_id: str
    agent_id: str
    detector_id: str
    detector_version: str = "1.0.0"
    threat_type: ThreatCategory
    title: str = Field(..., max_length=255)
    description: str
    severity: ThreatSeverity = ThreatSeverity.MEDIUM
    confidence: ThreatConfidence = ThreatConfidence.MEDIUM
    risk_contribution: float = Field(default=0.0, ge=0.0, le=100.0)
    evidence: dict[str, Any] = Field(default_factory=dict)
    affected_resource: str | None = None
    source_provenance: ProvenanceContext | None = None
    recommended_action: str = "Review agent activity and apply necessary restrictions."
    status: FindingStatus = FindingStatus.OPEN
    detected_at: datetime = Field(default_factory=lambda: datetime.now(UTC))

    model_config = {"from_attributes": True}


class CorrelatedThreat(BaseModel):
    """A composite threat synthesized by the Threat Correlation Engine."""

    correlation_id: uuid.UUID = Field(default_factory=uuid.uuid4)
    agent_id: str
    session_id: str | None = None
    threat_score: float = Field(..., ge=0.0, le=100.0)
    overall_severity: ThreatSeverity
    title: str
    explanation: str
    correlated_finding_ids: list[str] = Field(default_factory=list)
    recommended_response: str
    correlated_at: datetime = Field(default_factory=lambda: datetime.now(UTC))


class ThreatAnalysisResult(BaseModel):
    """Comprehensive result returned by the ThreatDetectionCoordinator."""

    analysis_id: uuid.UUID = Field(default_factory=uuid.uuid4)
    request_id: uuid.UUID
    agent_id: str
    findings: list[ThreatFinding] = Field(default_factory=list)
    correlations: list[CorrelatedThreat] = Field(default_factory=list)
    overall_threat_score: float = Field(default=0.0, ge=0.0, le=100.0)
    highest_severity: ThreatSeverity = ThreatSeverity.LOW
    detector_execution_times_ms: dict[str, float] = Field(default_factory=dict)
    incomplete_analysis: bool = False
    analysis_errors: list[str] = Field(default_factory=list)
    analyzed_at: datetime = Field(default_factory=lambda: datetime.now(UTC))

    @property
    def has_threats(self) -> bool:
        return len(self.findings) > 0
