"""
AgentShield AI — Database Configuration and Session Management.

Supports PostgreSQL (production) and SQLite (local development).
The active database URL is determined by AgentShieldSettings.effective_database_url.

Usage
─────
Backend startup:
    from agentshield.database.session import engine, get_async_session
    # Use get_async_session as a FastAPI dependency.

Alembic (migrations):
    Use the synchronous engine from agentshield.database.migrations.env
    (see alembic.ini / env.py generated by Task 9 setup).

Tenant isolation note (future phases):
    Row-level tenant isolation will be enforced at the repository layer by
    filtering every query on tenant_id.  The session itself does not carry
    tenant context — it is the responsibility of the authenticated request
    handler to supply the correct tenant_id from the verified JWT claim.
"""

from __future__ import annotations

import logging

from sqlalchemy.ext.asyncio import AsyncSession, async_sessionmaker, create_async_engine
from sqlalchemy.orm import DeclarativeBase

from agentshield.core.config import settings

logger = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# Engine
# ---------------------------------------------------------------------------

def _build_engine_kwargs() -> dict:
    """Return engine creation kwargs appropriate for the configured database."""
    db_url = settings.effective_database_url

    kwargs: dict = {
        "echo": settings.is_development,  # Log SQL only in development
    }

    if db_url.startswith("postgresql"):
        kwargs["pool_size"] = 10
        kwargs["max_overflow"] = 20
        kwargs["pool_pre_ping"] = True

    elif db_url.startswith("sqlite"):
        # SQLite requires connect_args for thread safety in async context
        kwargs["connect_args"] = {"check_same_thread": False}

    return kwargs


engine = create_async_engine(settings.effective_database_url, **_build_engine_kwargs())

AsyncSessionLocal = async_sessionmaker(
    bind=engine,
    class_=AsyncSession,
    expire_on_commit=False,
    autocommit=False,
    autoflush=False,
)


# ---------------------------------------------------------------------------
# Declarative base
# ---------------------------------------------------------------------------


class Base(DeclarativeBase):
    """Shared declarative base for all AgentShield ORM models.

    All models in agentshield.database.models must inherit from this base.
    The metadata attached here is used by Alembic for auto-generated migrations.
    """


# ---------------------------------------------------------------------------
# FastAPI dependency
# ---------------------------------------------------------------------------


async def get_async_session() -> AsyncSession:  # type: ignore[return]
    """FastAPI dependency that yields a database session per request.

    Usage:
        @router.get("/example")
        async def handler(db: AsyncSession = Depends(get_async_session)):
            ...
    """
    async with AsyncSessionLocal() as session:
        try:
            yield session
        except Exception:
            await session.rollback()
            raise
        finally:
            await session.close()


# ---------------------------------------------------------------------------
# Initialization helper (called at backend startup)
# ---------------------------------------------------------------------------


async def initialize_database() -> None:
    """Create all tables that do not yet exist.

    In production, this should be replaced by Alembic migrations.
    For local development it provides a zero-configuration bootstrap.
    """
    async with engine.begin() as conn:
        await conn.run_sync(Base.metadata.create_all)
    logger.info(
        "Database initialized",
        extra={"url": _redact_credentials(settings.effective_database_url)},
    )


def _redact_credentials(url: str) -> str:
    """Remove password from a database URL for safe logging."""
    try:
        from urllib.parse import urlparse, urlunparse

        parsed = urlparse(url)
        if parsed.password:
            netloc = parsed.netloc.replace(f":{parsed.password}@", ":***@")
            return urlunparse(parsed._replace(netloc=netloc))
    except Exception:
        pass
    return url
