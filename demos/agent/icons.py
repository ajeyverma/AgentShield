def get_pixmap(name: str, size: int = 16, color: str = "#000000") -> QPixmap:
    """Generate a crisp QPixmap from vector SVG with custom color and size."""
    svg_template = SVG_ICONS.get(name)
    if not svg_template:
        pix = QPixmap(size, size)
        pix.fill(QColor(0, 0, 0, 0))
        return pix

    svg_data = svg_template.replace("{color}", color).encode("utf-8")
    renderer = QSvgRenderer(QByteArray(svg_data))

    pixmap = QPixmap(size, size)
    pixmap.fill(QColor(0, 0, 0, 0))

    painter = QPainter(pixmap)
    renderer.render(painter)
    painter.end()

    return pixmap


def get_icon(name: str, size: int = 16, color: str = "#000000") -> QIcon:
    """Generate a QIcon from vector SVG."""
    return QIcon(get_pixmap(name, size, color))
